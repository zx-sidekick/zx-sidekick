#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_space_is_blank_and_the_letters_are_not() {
        assert!(CHARACTER_SET[..8].iter().all(|&b| b == 0));
        for letter in 33..128 {
            let at = (letter - 32) * 8;
            assert!(
                CHARACTER_SET[at..at + 8].iter().any(|&b| b != 0),
                "letter {letter:#x} is blank"
            );
        }
    }
}

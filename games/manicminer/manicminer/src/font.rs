/// The character set of the player's own 48K ROM, `rom`, when it is the ROM
/// ZX Sidekick knows ([`crate::facts::ROM_SHA1`]): the 768 bytes the game
/// would read from it. Any other file gives none.
#[must_use]
pub fn from_rom(rom: &[u8]) -> Option<[u8; 768]> {
    if zx_core::sha1::sha1_hex(rom) != crate::facts::ROM_SHA1 {
        return None;
    }
    let at = usize::from(crate::facts::FONT);
    rom.get(at..at + 768)?.try_into().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_letter_keeps_its_right_column_clear() {
        for (i, row) in OURS.iter().enumerate() {
            // The pound sign's crossbar and the copyright sign use the
            // whole width; everything else leaves the gap between letters.
            let letter = 32 + i / 8;
            if letter != 0x60 && letter != 0x7F && letter != 0x5F {
                assert_eq!(row & 1, 0, "letter {letter:#x} row {}", i % 8);
            }
        }
    }

    #[test]
    fn the_space_is_blank_and_the_letters_are_not() {
        assert!(OURS[..8].iter().all(|&b| b == 0));
        for letter in 33..128 {
            let at = (letter - 32) * 8;
            assert!(
                OURS[at..at + 8].iter().any(|&b| b != 0),
                "letter {letter:#x} is blank"
            );
        }
    }

    #[test]
    fn a_file_that_is_not_the_rom_gives_no_font() {
        assert_eq!(from_rom(&[0; 0x4000]), None);
        assert_eq!(from_rom(&[]), None);
    }
}
